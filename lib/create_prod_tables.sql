ON CONFLICT (et_event_type) DO NOTHING;

CREATE TABLE IF NOT EXISTS ta1_player_stats (
  a1_a1id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  a1_plid        INTEGER      NOT NULL,
  a1_group       VARCHAR(3)   NOT NULL,
  a1_mp_sessions INTEGER      NOT NULL DEFAULT 0,
  a1_mp_avg_pct  NUMERIC(5,2) NOT NULL DEFAULT 0,
  a1_vp_sessions INTEGER      NOT NULL DEFAULT 0,
  a1_vp_avg_vp   NUMERIC(5,2) NOT NULL DEFAULT 0,
  UNIQUE (a1_plid, a1_group)
);
CREATE INDEX IF NOT EXISTS idx_ta1_player_stats_plid ON ta1_player_stats (a1_plid);

CREATE TABLE IF NOT EXISTS ta2_partner_stats (
  a2_a2id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  a2_plid1       INTEGER      NOT NULL,
  a2_plid2       INTEGER      NOT NULL,
  a2_group       VARCHAR(3)   NOT NULL,
  a2_mp_sessions INTEGER      NOT NULL DEFAULT 0,
  a2_mp_avg_pct  NUMERIC(5,2) NOT NULL DEFAULT 0,
  a2_vp_sessions INTEGER      NOT NULL DEFAULT 0,
  a2_vp_avg_vp   NUMERIC(5,2) NOT NULL DEFAULT 0,
  UNIQUE (a2_plid1, a2_plid2, a2_group)
);
CREATE INDEX IF NOT EXISTS idx_ta2_partner_stats_plids ON ta2_partner_stats (a2_plid1, a2_plid2);
