-- Bridge Results Tracker Schema
-- Naming convention: txx_name tables, xx_columnname columns, xx_yy_id foreign keys

CREATE TABLE IF NOT EXISTS tpl_players (
  pl_plid             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pl_name             VARCHAR(100) NOT NULL UNIQUE,
  pl_nz_bridge_number INTEGER      NOT NULL DEFAULT 0,  -- 0 = no number assigned
  pl_club             VARCHAR(100) NOT NULL DEFAULT '',
  pl_rank             VARCHAR(100) NOT NULL DEFAULT '',
  pl_grade            VARCHAR(50)  NOT NULL DEFAULT '',
  pl_rating           NUMERIC(10,2) NOT NULL DEFAULT 0,
  pl_a_points         NUMERIC(10,2) NOT NULL DEFAULT 0,
  pl_b_points         NUMERIC(10,2) NOT NULL DEFAULT 0,
  pl_c_points         NUMERIC(10,2) NOT NULL DEFAULT 0,
  pl_last_updated     TIMESTAMP DEFAULT NOW(),
  pl_avg_percentage   NUMERIC(5,2) NOT NULL DEFAULT 0,  -- combined (all scoring types)
  pl_session_count    INTEGER      NOT NULL DEFAULT 0,  -- combined
  pl_mp_avg_percentage NUMERIC(5,2) NOT NULL DEFAULT 0,
  pl_mp_session_count  INTEGER      NOT NULL DEFAULT 0,
  pl_imp_avg_percentage NUMERIC(5,2) NOT NULL DEFAULT 0,
  pl_imp_session_count  INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tse_sessions (
  se_seid         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  se_date         DATE NOT NULL,
  se_day_of_week  VARCHAR(10) NOT NULL,
  se_scoring      VARCHAR(20) NOT NULL,                 -- 'MP' or 'IMP'
  se_source_id    INTEGER UNIQUE NOT NULL,
  se_date_seq     INTEGER      NOT NULL DEFAULT 0,
  se_session_type VARCHAR(20) NOT NULL DEFAULT 'club',  -- 'club' or 'online'
  se_status       VARCHAR(20) NOT NULL DEFAULT 'new',   -- 'new'|'fetched'|'processed'|'skipped'|'no-pairs'|'error'
  se_rounds       INTEGER      NOT NULL DEFAULT 0,      -- matches played (IMP/VP sessions); 0 = unknown
  se_name         VARCHAR(200) NOT NULL DEFAULT '',     -- scraped session label
  se_headevent_id INTEGER      NOT NULL DEFAULT 0,      -- parent event ID (headeventid) for grouping
  se_shid         INTEGER      NOT NULL DEFAULT 0       -- FK to tsh_session_header.sh_shid
);

CREATE TABLE IF NOT EXISTS tsh_session_header (
  sh_shid         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sh_headevent_id INTEGER      NOT NULL UNIQUE,         -- AKBC headeventid
  sh_name         VARCHAR(200) NOT NULL DEFAULT '',     -- event label from level-1 page (e.g. "EASTER CONGRESS TEAMS")
  sh_date         DATE,                                 -- date from level-1 row (null for standalone imports)
  sh_year         INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tpa_partners (
  pa_paid         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pa_plid1        INTEGER NOT NULL,
  pa_plid2        INTEGER NOT NULL,
  pa_sessions     INTEGER NOT NULL DEFAULT 0,       -- combined
  pa_avg_pct      NUMERIC(5,2) NOT NULL DEFAULT 0,  -- combined
  pa_mp_sessions  INTEGER      NOT NULL DEFAULT 0,
  pa_mp_avg_pct   NUMERIC(5,2) NOT NULL DEFAULT 0,
  pa_imp_sessions INTEGER      NOT NULL DEFAULT 0,
  pa_imp_avg_pct  NUMERIC(5,2) NOT NULL DEFAULT 0,
  pa_last_updated TIMESTAMP DEFAULT NOW(),
  UNIQUE (pa_plid1, pa_plid2)
);

CREATE TABLE IF NOT EXISTS tre_results (
  re_reid         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  re_seid         INTEGER,
  re_plid         INTEGER,
  re_partner_plid INTEGER,
  re_pairid       INTEGER,
  re_percentage   DECIMAL(5,2) NOT NULL,
  re_match_num    INTEGER      NOT NULL DEFAULT 1  -- match number within session (1 for single-match sessions)
);

-- Partial unique indexes (exclude default/unset values)
CREATE UNIQUE INDEX IF NOT EXISTS uq_pl_nz_bridge_number ON tpl_players (pl_nz_bridge_number) WHERE pl_nz_bridge_number > 0;

-- trw_results_raw: staging table — raw pair names from AKBC before player ID resolution
CREATE TABLE IF NOT EXISTS trw_results_raw (
  rw_rwid       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rw_seid       INTEGER NOT NULL,
  rw_name1      VARCHAR(100) NOT NULL,  -- alphabetically first
  rw_name2      VARCHAR(100) NOT NULL,  -- alphabetically second
  rw_percentage DECIMAL(5,2) NOT NULL,  -- MP: scraped pair %; IMP: 0 (unused)
  rw_vp         NUMERIC(6,2),           -- VP for this match (0–20 scale); NULL for MP
  rw_match_num  INTEGER      NOT NULL DEFAULT 1  -- match number within session (1 for single-match sessions)
);

-- tam_players_ambiguous: players where nzbridge.co.nz returned multiple matches for review
CREATE TABLE IF NOT EXISTS tam_players_ambiguous (
  am_amid        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  am_search_name VARCHAR(100) NOT NULL DEFAULT '',
  am_nz_number   INTEGER      NOT NULL DEFAULT 0,
  am_nz_name     VARCHAR(100) NOT NULL DEFAULT '',
  am_club        VARCHAR(100) NOT NULL DEFAULT '',
  am_created     TIMESTAMP DEFAULT NOW()
);


-- trk_ranks: distinct player rank values for filtering
CREATE TABLE IF NOT EXISTS trk_ranks (
  rk_rkid  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rk_rank  VARCHAR(100) NOT NULL UNIQUE
);

-- tcl_clubs: distinct player club values for filtering
CREATE TABLE IF NOT EXISTS tcl_clubs (
  cl_clid  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cl_club  VARCHAR(100) NOT NULL UNIQUE
);

-- tgr_grades: distinct player grade values for filtering
CREATE TABLE IF NOT EXISTS tgr_grades (
  gr_grid  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gr_grade VARCHAR(50) NOT NULL UNIQUE
);

-- ── Raw scrape tables (ts*) ──────────────────────────────────────────────────
-- These store exactly what is fetched from AKBC. Processed tables are rebuilt
-- from these without further web requests.

CREATE TABLE IF NOT EXISTS ts1_main (
  s1_s1id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s1_year       INTEGER      NOT NULL,
  s1_date       DATE,
  s1_event_name VARCHAR(200) NOT NULL DEFAULT '',
  s1_event_id   INTEGER,
  s1_type       VARCHAR(20),  -- 'headevent' | 'teamresults' | 'resultsbm' | null
  s1_url        VARCHAR(300),
  s1_status     VARCHAR(20),  -- null | 'scraped' | 'built'
  s1_raw_count  INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ts2_team_matchdata (
  s2_s2id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s2_event_id INTEGER      NOT NULL,
  s2_url      VARCHAR(300),
  s2_place    INTEGER      NOT NULL DEFAULT 0,
  s2_team_num INTEGER      NOT NULL,
  s2_vp       DECIMAL(5,2)[] NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS ts3_team_members (
  s3_s3id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s3_event_id     INTEGER      NOT NULL,
  s3_url          VARCHAR(300),
  s3_team_num     INTEGER      NOT NULL,
  s3_team_name    VARCHAR(100) NOT NULL DEFAULT '',
  s3_player_names VARCHAR(100)[] NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS ts4_team_rounds (
  s4_s4id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s4_event_id      INTEGER      NOT NULL,
  s4_url           VARCHAR(300),
  s4_team_num      INTEGER      NOT NULL,
  s4_opponent_nums INTEGER[]    NOT NULL DEFAULT '{}',
  s4_vps           DECIMAL(5,2)[] NOT NULL DEFAULT '{}'
);


CREATE TABLE IF NOT EXISTS ts6_session (
  s6_s6id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s6_event_id   INTEGER      NOT NULL DEFAULT 0,
  s6_source_id  INTEGER      NOT NULL,
  s6_url        VARCHAR(300),
  s6_title      VARCHAR(200) NOT NULL DEFAULT '',
  s6_direction  VARCHAR(5),
  s6_place      INTEGER      NOT NULL DEFAULT 0,
  s6_percentage DECIMAL(5,2) NOT NULL,
  s6_pair_names VARCHAR(200) NOT NULL DEFAULT '',
  s6_pair_num   INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ts5_session_header (
  s5_s5id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s5_event_id     INTEGER      NOT NULL,
  s5_date         DATE,
  s5_session_name VARCHAR(200) NOT NULL DEFAULT '',
  s5_source_id    INTEGER,
  s5_type         VARCHAR(20),  -- 'resultsbm' | 'multisession' | null
  s5_url          VARCHAR(300)
);

CREATE INDEX IF NOT EXISTS idx_ts2_event  ON ts2_team_matchdata (s2_event_id);
CREATE INDEX IF NOT EXISTS idx_ts3_event  ON ts3_team_members (s3_event_id);
CREATE INDEX IF NOT EXISTS idx_ts4_event  ON ts4_team_rounds (s4_event_id);
CREATE INDEX IF NOT EXISTS idx_ts6_source ON ts6_session (s6_source_id);
CREATE INDEX IF NOT EXISTS idx_ts6_event  ON ts6_session (s6_event_id);
CREATE INDEX IF NOT EXISTS idx_ts5_event  ON ts5_session_header (s5_event_id);

CREATE TABLE IF NOT EXISTS ts7_nz_players (
  s7_s7id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s7_name        VARCHAR(100) NOT NULL UNIQUE,      -- Title Case name; sourced from ts3/ts6 session data
  s7_nz_number   INTEGER,                           -- NULL until found via nzbridge lookup
  s7_club        VARCHAR(100) NOT NULL DEFAULT '',
  s7_rank        VARCHAR(100) NOT NULL DEFAULT '',
  s7_grade       VARCHAR(50)  NOT NULL DEFAULT '',
  s7_rating      NUMERIC(10,2) NOT NULL DEFAULT 0,
  s7_a_points    NUMERIC(10,2) NOT NULL DEFAULT 0,
  s7_b_points    NUMERIC(10,2) NOT NULL DEFAULT 0,
  s7_c_points    NUMERIC(10,2) NOT NULL DEFAULT 0,
  s7_status      VARCHAR(20)  NOT NULL DEFAULT 'not_found'  -- 'found' | 'not_found'
);

CREATE TABLE IF NOT EXISTS ts8_nz_results (
  s8_s8id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s8_nz_number      INTEGER      NOT NULL,
  s8_date           DATE,
  s8_club           VARCHAR(100) NOT NULL DEFAULT '',
  s8_event_name     VARCHAR(200) NOT NULL DEFAULT '',
  s8_place          VARCHAR(10)  NOT NULL DEFAULT '',
  s8_score_value    NUMERIC(10,2) NOT NULL DEFAULT 0,
  s8_score_type     VARCHAR(5)   NOT NULL DEFAULT '',  -- 'PCT' | 'VP'
  s8_a_points       NUMERIC(10,2),
  s8_b_points       NUMERIC(10,2),
  s8_c_points       NUMERIC(10,2),
  s8_tournament     VARCHAR(10),   -- masterpoint code e.g. '10A', '8B'
  s8_type           VARCHAR(10),   -- 'Final' | 'Session' | NULL
  s8_session_number INTEGER,       -- session number or NULL
  s8_restricted     VARCHAR(20),   -- 'restricted' | 'open' | ''
  s8_event_type     VARCHAR(20),   -- 'pairs' | 'teams' | 'swiss_pairs' | 'swiss_teams' | ''
  s8_category       VARCHAR(30)    -- 'Provincial' | 'Championship' | 'Junior' | 'Intermediate' | 'Open' | ''
);
CREATE INDEX IF NOT EXISTS idx_ts8_nz_number ON ts8_nz_results (s8_nz_number);

-- ts9_partners: pair combinations extracted from ts6 session data, staged for tpa_partners
CREATE TABLE IF NOT EXISTS ts9_partners (
  s9_s9id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  s9_name1  VARCHAR(100) NOT NULL,  -- alphabetically first (references ts7 s7_name)
  s9_name2  VARCHAR(100) NOT NULL,  -- alphabetically second
  UNIQUE (s9_name1, s9_name2)
);

-- tlg_logging: required by nextjs-shared write_Logging
CREATE TABLE IF NOT EXISTS tlg_logging (
  lg_lgid         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lg_datetime     TIMESTAMPTZ,
  lg_msg          TEXT,
  lg_functionname VARCHAR(128),
  lg_caller       VARCHAR(128),
  lg_severity     VARCHAR(4)
);
